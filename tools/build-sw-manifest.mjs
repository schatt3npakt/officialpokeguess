#!/usr/bin/env node
/**
 * Generates www/precache-manifest.js: the list of app-shell files the service worker
 * precaches, plus a version hash of their contents. Run before every deployment:
 *   npm run sw
 * Pokémon artwork, icons and cries are excluded (cached at runtime on first use).
 */
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../www/', import.meta.url))

const EXCLUDE = [
  /^assets\/pokemon\//,
  /^assets\/img\/badges\//,
  /^assets\/sfx\/bgm\.ogg$/,
  /^service-worker\.js$/,
  /^precache-manifest\.js$/,
  /^robots\.txt$/,
  /(^|\/)\./
]

async function walk(dir) {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...(await walk(full)))
    else out.push(relative(root, full).split(sep).join('/'))
  }
  return out
}

const files = (await walk(root)).filter((f) => !EXCLUDE.some((re) => re.test(f))).sort()
const hash = createHash('sha256')
for (const file of files) {
  hash.update(file)
  hash.update(await readFile(join(root, file)))
}
const version = hash.digest('hex').slice(0, 12)

const body = `// Generated by tools/build-sw-manifest.mjs - do not edit. Run \`npm run sw\` after changing www/.
self.__PRECACHE = ${JSON.stringify({ version, files: ['./', ...files] }, null, 2)}
`
await writeFile(join(root, 'precache-manifest.js'), body)
console.log(`precache-manifest.js: ${files.length} files, version ${version}`)
